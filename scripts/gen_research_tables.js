/*
 * Builds the "research workbook" import (Equitas format: Card Fee, Clarifi Data, Card Details, categoryCondition,
 * Rewards & Benefits, MCC, Sources, Read Me, Reward Calculations) from the sheet/column layout of a sample file.
 * Only headers are read, never the data.
 *   node scripts/gen_research_tables.js [workbook.xlsx]
 * writes supabase/research_tables.sql, js/research_schema.js, import_template_research.xlsx
 */
const fs = require('fs'), path = require('path'), XLSX = require('xlsx'), ExcelJS = require('exceljs');
const ROOT = path.join(__dirname, '..');
const SRC = process.argv[2] || path.join(ROOT, 'test', 'Equitas_Small_Finance_Bank_Credit_Cards (1).xlsx');

const snake = (s) => String(s).replace(/%/g, ' pct ').replace(/&/g, ' and ').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
// blank / misspelt headers in the source file
const FIX = { 'Card Fee': { 9: 'notes', 10: 'source' }, };
const RENAME = { spent_duration_of_anual: 'spent_duration_of_annual' };
const NUMERIC = ['maximum_monthly_fuel_surcharge_waiver_rs', 'maximum_annual_fuel_surcharge_waiver_rs'];
const FLAG_SHEET = 'Clarifi Data', FLAG_FROM = 7;           // category Y / NA columns start at the 8th column
const FLAGS = ['Y', 'N', 'NA'];

const wb = XLSX.readFile(SRC, { sheetRows: 2 });
const schema = {}, sql = ['-- Generated by scripts/gen_research_tables.js. One table per research sheet, admin-only RLS.', 'begin;'];
for (const sheet of wb.SheetNames) {
    const g = XLSX.utils.sheet_to_json(wb.Sheets[sheet], { header: 1, defval: '' });
    const hdr = (g[0] || []).slice(); while (hdr.length < Math.max(...g.map((r) => r.length))) hdr.push('');   // blank-headed columns still carry data
    const used = {};
    const cols = [], headers = [], types = [];
    hdr.forEach((h, i) => {
        let c = (FIX[sheet] && FIX[sheet][i]) || snake(h);
        if (!c) return;
        c = RENAME[c] || c;
        used[c] = (used[c] || 0) + 1; if (used[c] > 1) c += '_' + used[c];
        const isFlag = sheet === FLAG_SHEET && i >= FLAG_FROM;
        cols.push(c); headers.push(String(h).trim() || c);
        types.push(NUMERIC.includes(c) ? 'numeric(12,2)' : isFlag ? 'varchar(3)' : 'text');
    });
    const table = 'rs_' + snake(sheet);
    schema[sheet] = { table, label: sheet.trim(), cardIdCol: null, headers, cols, types, required: [] /* layout is validated, not the content */, flags: sheet === FLAG_SHEET ? cols.slice(FLAG_FROM) : [] };;
    sql.push(`drop table if exists ${table};`);
    sql.push(`create table ${table} (\n  id uuid primary key default gen_random_uuid(),\n${cols.map((c, i) => `  ${c} ${types[i]}`).join(',\n')},\n  bank text,\n  source_file text,\n  imported_at timestamptz default now()\n);`);
    sql.push(`create index ${table}_bank_idx on ${table} (bank);`);
    schema[sheet].flags.forEach((c) => sql.push(`alter table ${table} add constraint ${table}_${c.slice(0, 30)}_chk check (${c} is null or ${c} in ('Y','N','NA'));`));
    sql.push(`alter table ${table} enable row level security;`);
    sql.push(`create policy ${table}_admin_all on ${table} for all to authenticated using (is_admin()) with check (is_admin());`);
}
sql.push('commit;');
fs.writeFileSync(path.join(ROOT, 'supabase', 'research_tables.sql'), sql.join('\n') + '\n');
fs.writeFileSync(path.join(ROOT, 'js', 'research_schema.js'),
    '// Generated by scripts/gen_research_tables.js: sheet/column layout of the research workbook (Equitas format).\nwindow.RESEARCH_SCHEMA = ' + JSON.stringify(schema, null, 1) + ';\n');

// template with column validation
const out = new ExcelJS.Workbook();
for (const [sheet, def] of Object.entries(schema)) {
    const ws = out.addWorksheet(sheet.trim().slice(0, 31));
    ws.addRow(def.headers).font = { bold: true };
    ws.views = [{ state: 'frozen', ySplit: 1 }];
    def.cols.forEach((c, i) => {
        ws.getColumn(i + 1).width = Math.min(40, Math.max(16, def.headers[i].length + 2));
        let dv = null;
        if (def.flags.includes(c)) dv = { type: 'list', allowBlank: true, formulae: ['"' + FLAGS.join(',') + '"'], errorTitle: 'Pick from the list', error: 'Use Y, N or NA' };
        else if (def.types[i].startsWith('numeric')) dv = { type: 'decimal', operator: 'between', allowBlank: true, formulae: [0, 1e9], errorTitle: 'Number', error: def.headers[i] + ' must be a number' };
        if (dv) { dv.showErrorMessage = true; for (let r = 2; r <= 1000; r++) ws.getCell(r, i + 1).dataValidation = dv; }
    });
}
out.xlsx.writeFile(path.join(ROOT, 'import_template_research.xlsx')).then(() => console.log(Object.entries(schema).map(([s, d]) => `${s} -> ${d.table} (${d.cols.length} cols)`).join('\n')));
