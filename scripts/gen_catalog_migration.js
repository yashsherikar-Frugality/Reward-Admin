// Builds supabase/catalog_v5_migration.sql + js/schema_catalog.js from test/consolidated_fields_catalog-v5.xlsx
// and the live column list / data profile. Usage: node scripts/gen_catalog_migration.js <catalog.json>
// (catalog.json = {rows, live} dumped from the xlsx and information_schema).
const fs = require('fs'), { Client } = require('pg');
fs.readFileSync('.env', 'utf8').split(/\r?\n/).forEach(l => { const m = l.match(/^(\w+)=(.*)$/); if (m) process.env[m[1]] = m[2]; });
const { rows, live } = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const q = s => s.replace(/'/g, "''");
const PH = "('', 'n/a', 'na', 'nan', 'null', 'none', '-', '0.0')";

function parseFmt(fmt) {
  const f = String(fmt || '');
  const base = (f.match(/^(VARCHAR|NUMERIC|INTEGER|BOOLEAN|DATE|TEXT|JSONB|UUID|TIMESTAMPTZ)/i) || [])[1];
  const a = f.match(/\((\d+)(?:,\s*(\d+))?\)/) || [];
  const def = (f.match(/DEFAULT\s+('[^']*'|[\w.]+)/i) || [])[1];
  return { base: (base || '').toUpperCase(), n: a[1] && +a[1], s: a[2] && +a[2], def };
}
const sqlType = p => p.base === 'VARCHAR' ? `varchar(${p.n})` : p.base === 'NUMERIC' ? `numeric(${p.n},${p.s || 0})` : p.base.toLowerCase();
const liveBase = t => ({ 'character varying': 'VARCHAR', numeric: 'NUMERIC', bigint: 'INTEGER', integer: 'INTEGER', boolean: 'BOOLEAN', date: 'DATE', text: 'TEXT', jsonb: 'JSONB', uuid: 'UUID', 'timestamp with time zone': 'TIMESTAMPTZ' }[t]);

const HELPERS = `-- Generated by scripts/gen_catalog_migration.js from consolidated_fields_catalog-v5.xlsx
-- Runs in one transaction. Originals are copied to schema backup_20261118 first.
begin;
create or replace function catalog_to_numeric(val text, p int, s int, as_pct boolean default false) returns numeric as $$
declare t text; v numeric; lim numeric;
begin
  if val is null then return null; end if;
  t := trim(val);
  if lower(t) in ${PH} then return null; end if;
  t := regexp_replace(regexp_replace(t, '\\s*\\+$', ''), '\\s*(years?|yrs?)$', '', 'i');
  if lower(t) = 'nil' then return 0; end if;
  v := clean_amount_units(t);
  if v is null and t ~* '^(₹|rs\\.?|inr)?\\s*[0-9][0-9,]*(\\.[0-9]+)?\\s*[lkm]$' then
    v := regexp_replace(regexp_replace(t, '^(₹|rs\\.?|inr)\\s*', '', 'i'), '[,lkmLKM\\s]', '', 'g')::numeric
         * case lower(right(t, 1)) when 'l' then 100000 when 'k' then 1000 else 1000000 end;
  end if;
  if v is null and t ~ '^[0-9]+(\\.[0-9]+)?\\s*%$' then v := regexp_replace(t, '\\s*%$', '')::numeric; end if;
  if v is null then return null; end if;
  if as_pct and v > 0 and v <= 1 and t !~ '%' then v := v * 100; end if;
  lim := 10 ^ (p - s);
  if abs(v) >= lim then return null; end if;
  return round(v, s);
end $$ language plpgsql immutable;
create or replace function catalog_to_int(val text) returns integer as $$
declare v numeric;
begin
  v := catalog_to_numeric(val, 18, 0);
  if v is null or abs(v) > 2147483647 then return null; end if;
  return v::integer;
end $$ language plpgsql immutable;
create or replace function catalog_to_bool(val text) returns boolean as $$
declare t text;
begin
  if val is null then return null; end if;
  t := lower(trim(val));
  if t in ${PH} then return null; end if;
  if t in ('true','t','yes','y','1') or t ~ '^yes\\y' or t ~ '^automatic' or t ~ '^included' then return true; end if;
  if t in ('false','f','no','n','0') or t ~ '^no\\y' then return false; end if;
  return null;
end $$ language plpgsql immutable;
create or replace function catalog_to_date(val text) returns date as $$
declare t text;
begin
  if val is null then return null; end if;
  t := trim(val);
  if t ~ '^\\d{4}-\\d{2}-\\d{2}' then return left(t, 10)::date; end if;
  if t ~ '^\\d{1,2}[/-]\\d{1,2}[/-]\\d{4}$' then return to_date(t, 'DD-MM-YYYY'); end if;
  return null;
exception when others then return null;
end $$ language plpgsql immutable;
`;

(async () => {
  const c = new Client({ ssl: { rejectUnauthorized: false } }); await c.connect();
  await c.query(HELPERS.replace('begin;', '')); // converters must exist to profile the data (harmless, idempotent)
  const out = [HELPERS], map = {}, lists = [], report = [];
  const emit = s => out.push(s);
  const tbls = [...new Set(rows.map(r => r.table))];

  emit('create schema if not exists backup_20261118;');
  tbls.forEach(t => emit(`create table backup_20261118.${t} as table public.${t};`));
  emit('');

  for (const t of tbls) {
    const tmap = map[t] = { columns: {}, dropped: [], added: [] };
    for (const r of rows.filter(r => r.table === t)) {
      const exists = live[t] && live[t][r.field] !== undefined;
      const review = String(r.review || '');
      const p = parseFmt(r.fmt);
      if (/^not/i.test(review)) {
        if (!exists) continue;
        if (t === 'offers' && !['merchant', 'mcc'].includes(r.field))
          emit(`update offers set reward_fields = coalesce(reward_fields,'{}'::jsonb) || jsonb_build_object('${r.field}', ${r.field}) where ${r.field} is not null and lower(trim(${r.field})) not in ${PH} and not (coalesce(reward_fields,'{}'::jsonb) ? '${r.field}');`);
        emit(`alter table ${t} drop column ${r.field};`);
        tmap.dropped.push(r.field);
        continue;
      }
      const target = r.sug || r.field;
      if (!exists) {
        emit(`alter table ${t} add column ${target} ${sqlType(p)}${p.def ? ' default ' + p.def : ''};`);
        tmap.added.push(target);
        tmap.columns[target] = { from: null, type: sqlType(p) };
        continue;
      }
      const lt = live[t][r.field], lbase = liveBase(lt);
      let newType = null, kind = null;
      if (p.base === 'VARCHAR' && lbase === 'VARCHAR') {
        const ml = +(await c.query(`select coalesce(max(length("${r.field}")),0) m from ${t}`)).rows[0].m;
        newType = ml > p.n ? 'text' : sqlType(p);
        if (ml > p.n) report.push(`${t}.${r.field}: longest value ${ml} > varchar(${p.n}); kept as text`);
        kind = 'text';
      } else if (['NUMERIC', 'INTEGER', 'BOOLEAN', 'DATE'].includes(p.base) && lbase === 'VARCHAR') {
        kind = p.base; newType = sqlType(p);
      } else if (p.base === 'TEXT' && lbase === 'VARCHAR') { kind = 'text'; newType = 'text'; }
      if (newType) {
        if (kind !== 'text') {
          const pct = r.field === 'apr';
          const conv = kind === 'NUMERIC' ? `catalog_to_numeric(${r.field}, ${p.n}, ${p.s || 0}, ${pct})`
            : kind === 'INTEGER' ? `catalog_to_int(${r.field})` : kind === 'BOOLEAN' ? `catalog_to_bool(${r.field})` : `catalog_to_date(${r.field})`;
          const where = `${r.field} is not null and lower(trim(${r.field})) not in ${PH} and ${conv} is null`;
          const fail = +(await c.query(`select count(*) n from ${t} where ${where}`)).rows[0].n;
          const tot = +(await c.query(`select count(*) n from ${t} where ${r.field} is not null and lower(trim(${r.field})) not in ${PH}`)).rows[0].n;
          const lst0 = String(r.list || '');
          if ((kind !== 'BOOLEAN' && lst0 && !/^N\/A/.test(lst0)) || (tot && fail / tot > 0.2)) {
            report.push(`${t}.${r.field}: type NOT changed to ${newType} (${lst0 && !/^N\/A/.test(lst0) ? 'categorical list' : fail + ' of ' + tot + ' values are free text'}); kept ${lt}${target !== r.field ? ', renamed to ' + target : ''}`);
            newType = null;
          }
          if (newType && fail > 0) {
            emit(`alter table ${t} add column ${target}_raw text;`);
            emit(`update ${t} set ${target}_raw = ${r.field} where ${where};`);
            report.push(`${t}.${r.field} -> ${target} (${newType}): ${fail} value(s) not convertible; originals kept in ${target}_raw`);
            tmap.columns[target + '_raw'] = { from: null, type: 'text' };
          }
          if (newType) { emit(`alter table ${t} alter column ${r.field} drop default;`); emit(`alter table ${t} alter column ${r.field} type ${newType} using ${conv};`); }
        } else emit(`alter table ${t} alter column ${r.field} type ${newType};`);
      }
      if (p.def) emit(`alter table ${t} alter column ${r.field} set default ${p.def};`);
      if (target !== r.field) emit(`alter table ${t} rename column ${r.field} to ${target};`);
      const tgtType = newType || lt;
      tmap.columns[target] = { from: r.field, type: tgtType };
      const lst = String(r.list || '');
      if (lst && !/^N\/A/.test(lst)) {
        let items = [...lst.matchAll(/'([^']+)'/g)].map(m => m[1]);
        if (!items.length) items = (lst.match(/\[([^\]]*)\]/) || ['', ''])[1].split(',').map(s => s.trim()).filter(Boolean);
        if (items.length) lists.push({ t, col: target, items, text: /varchar|text|character/i.test(tgtType) });
      }
    }
  }

  emit(`
create table if not exists catalog_lists (table_name text, column_name text, value text, sort int, primary key (table_name, column_name, value));
delete from catalog_lists;
alter table catalog_lists enable row level security;
drop policy if exists catalog_lists_admin_all on catalog_lists;
create policy catalog_lists_admin_all on catalog_lists for all to authenticated using (is_admin()) with check (is_admin());`);
  for (const l of lists) {
    l.items.forEach((v, i) => emit(`insert into catalog_lists values ('${l.t}','${l.col}','${q(v)}',${i}) on conflict do nothing;`));
    if (!l.text) continue;
    const arr = `array[${l.items.map(v => `'${q(v)}'`).join(',')}]`;
    l.items.forEach(v => emit(`update ${l.t} set ${l.col} = '${q(v)}' where ${l.col} <> '${q(v)}' and lower(trim(${l.col})) = lower('${q(v)}');`));
    const cname = `chk_${l.t}_${l.col}`.slice(0, 60);
    emit(`do $$ begin
  if not exists (select 1 from ${l.t} where ${l.col} is not null and lower(${l.col}) not in ('n/a','na') and ${l.col} <> all(${arr})) then
    alter table ${l.t} drop constraint if exists ${cname};
    alter table ${l.t} add constraint ${cname} check (${l.col} is null or lower(${l.col}) in ('n/a','na') or ${l.col} = any(${arr}));
  else raise notice 'list not enforced (existing values differ): ${l.t}.${l.col}';
  end if;
end $$;`);
  }
  emit('commit;');

  fs.writeFileSync('supabase/catalog_v5_migration.sql', out.join('\n') + '\n');
  fs.writeFileSync('js/schema_catalog.js', '// Generated by scripts/gen_catalog_migration.js: DB column map/types/lists from consolidated_fields_catalog-v5.xlsx\nwindow.SCHEMA_CATALOG = ' + JSON.stringify({ tables: map, lists: lists.map(({ t, col, items }) => ({ t, col, items })) }, null, 1) + ';\n');
  fs.writeFileSync('supabase/catalog_v5_report.txt', report.join('\n') + '\n');
  console.log(lists.length, 'lists;', report.length, 'conversion notes'); console.log(report.join('\n'));
  await c.end();
})();
