/*
 * Strict rebuild of the benefit/card tables straight from consolidated_fields_catalog-v5.xlsx (PM).
 * Column names = "Suggested field name", types = "Suggested format" (incl. PRIMARY KEY / REFERENCES / UNIQUE / DEFAULT),
 * dropdown lists = CHECK constraints. No *_raw columns, no text fallbacks.
 *   node scripts/gen_catalog_rebuild.js <catalog.json>
 * writes supabase/catalog_v5_rebuild.sql, js/schema_catalog.js, supabase/catalog_v5_rebuild_report.txt
 */
const fs = require('fs');
const { rows } = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const q = (s) => String(s).replace(/'/g, "''");
const SKIP_TABLES = ['wb_contactless', 'benefit_numeric_stats', 'id_rename_map'];   // PM: no contactless sheet; the other two are unchanged

// PM "Later changes" (Cards_DB workbook) override the catalog / add columns
const CARD_EXTRA = [['rp_cashback_value', 'NUMERIC(8,4)'], ['rp_mile_value', 'NUMERIC(8,4)'], ['rp_mile_name', 'VARCHAR(100)'], ['rp_program_value', 'NUMERIC(8,4)'], ['rp_program_name', 'VARCHAR(100)'],
  ['earn_points_domestic', 'NUMERIC(8,4)'], ['earn_points_international', 'NUMERIC(8,4)'], ['spend_mile_rate', 'NUMERIC(8,4)'], ['spend_mile_name', 'VARCHAR(100)'], ['spend_program_rate', 'NUMERIC(8,4)'], ['spend_program_name', 'VARCHAR(100)']];
const PRODUCT_TYPES = ['Commercial / Business', 'Unsecured – Core', 'Unsecured – Core / LTF', 'Secured / FD-Backed', 'Unsecured – Core ⚠', 'Unsecured - Elite', 'Unsecured – Invite-Only', 'Unsecured – Premium', 'Unsecured - Super Premium'];

const tables = [...new Set(rows.map((r) => r.table))].filter((t) => !SKIP_TABLES.includes(t));
const order = ['cards', 'offers', 'mcc_rules', ...tables.filter((t) => !['cards', 'offers', 'mcc_rules'].includes(t))];
const sql = ['-- Generated by scripts/gen_catalog_rebuild.js. Drops and recreates the catalog tables strictly per the PM catalog.', 'begin;',
  `drop table if exists ${order.join(', ')}, wb_contactless cascade;`];
const map = {}, lists = [], report = [];

for (const t of order) {
  const rs = rows.filter((r) => r.table === t);
  const tm = map[t] = { columns: {}, dropped: [], added: [] };
  const defs = [], checks = [];
  for (const r of rs) {
    if (/^not/i.test(String(r.review))) { tm.dropped.push(r.field); continue; }
    const name = r.sug || r.field;
    let fmt = String(r.fmt).trim();
    const lst = String(r.list || '');
    let items = [];
    if (lst && !/^N\/A/.test(lst)) {
      items = [...lst.matchAll(/'([^']+)'/g)].map((m) => m[1]);
      if (!items.length) items = (lst.match(/\[([^\]]*)\]/) || ['', ''])[1].split(',').map((s) => s.trim()).filter(Boolean);
    }
    if (t === 'cards' && name === 'product_type') items = PRODUCT_TYPES;
    const isBool = /^BOOLEAN/i.test(fmt);
    const numList = items.length && /^(NUMERIC|INTEGER)/i.test(fmt) && items.every((v) => v !== '' && !isNaN(Number(v)));   // [30, 45, 60, 90]: numeric column, numeric CHECK
    if (items.length && !isBool && !numList && /^(NUMERIC|INTEGER|DATE)/i.test(fmt)) {
      report.push(`${t}.${name}: catalog type ${fmt} conflicts with its dropdown list; built as VARCHAR(255) with the list as CHECK`);
      fmt = 'VARCHAR(255)';
    }
    if (/^UUID PRIMARY KEY/i.test(fmt)) fmt = 'UUID PRIMARY KEY DEFAULT gen_random_uuid()';
    if (/^TIMESTAMPTZ/i.test(fmt) && /^(created_at|updated_at|imported_at)$/.test(name)) fmt += ' DEFAULT now()';
    if (/PRIMARY KEY/i.test(fmt) === false && name === 'card_id' && !/REFERENCES/i.test(fmt)) fmt += '';
    defs.push(`  ${name} ${fmt}`);
    tm.columns[name] = { from: r.field, type: fmt.replace(/ (PRIMARY KEY|UNIQUE|DEFAULT|REFERENCES).*$/i, '').toLowerCase() };
    if (!rs.length || String(r.review) === 'Missing') tm.added.push(name);
    if (items.length && !isBool) {
      checks.push(`  constraint chk_${t}_${name}`.slice(0, 66) + ` check (${name} is null or ${name} = any(array[${items.map((v) => (numList ? String(Number(v)) : `'${q(v)}'`)).join(',')}]))`);
    }
    if (items.length) lists.push({ t, col: name, items });
  }
  if (t === 'cards') CARD_EXTRA.forEach(([n, ty]) => { defs.push(`  ${n} ${ty}`); tm.columns[n] = { from: null, type: ty.toLowerCase() }; tm.added.push(n); });
  sql.push(`create table ${t} (\n${[...defs, ...checks].join(',\n')}\n);`);
  if (rs.some((r) => /^card_id$/.test(r.sug || r.field)) && t !== 'cards') sql.push(`create index ${t}_card_idx on ${t} (card_id);`);
  sql.push(`alter table ${t} enable row level security;`);
  sql.push(`create policy ${t}_admin_all on ${t} for all to authenticated using (is_admin()) with check (is_admin());`);
}

// dropdown reference table (kept in sync with the CHECK constraints and the app's dropdowns)
sql.push('delete from catalog_lists;');
lists.forEach((l) => l.items.forEach((v, i) => sql.push(`insert into catalog_lists values ('${l.t}','${l.col}','${q(v)}',${i}) on conflict do nothing;`)));
sql.push('commit;');

fs.writeFileSync('supabase/catalog_v5_rebuild.sql', sql.join('\n') + '\n');
fs.writeFileSync('js/schema_catalog.js', '// Generated by scripts/gen_catalog_rebuild.js: DB column map/types/lists from consolidated_fields_catalog-v5.xlsx (+ PM Cards_DB changes)\nwindow.SCHEMA_CATALOG = ' + JSON.stringify({ tables: map, lists }, null, 1) + ';\n');
fs.writeFileSync('supabase/catalog_v5_rebuild_report.txt', report.join('\n') + '\n');
console.log(order.length, 'tables;', lists.length, 'lists;', report.length, 'type/list conflicts');
console.log(report.join('\n'));
